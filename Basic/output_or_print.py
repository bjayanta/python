# Print Text
print("Hello World!")

# Double Quotes
print("Hello World!")

# Single Quotes
print('Hello World!')

# Print Without a New Line
print("Jayanta", end="")
print("Biswas")

# Print Separator
print("Hello", "World!", "Biswas", sep="-")

# Print End
print("Hello", "World!", end="!")

# Print Format
print("Hello", "World!", end="!")
print("Jayanta", "Biswas", end="!")

# Print Numbers
print(3)
print(358)
print(50000)

print(3 + 3)
print(2 * 5)

# Mix Text and Numbers
print("I am", 35, "years old.")

print('Hello', 'World')
